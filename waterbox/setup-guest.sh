#!/bin/sh
# Configures the GUEST (core.wbx) build: generates a meson cross file for
# miniBox's musl guest toolchain (plain C - GPGX needs no libstdc++) and sets
# up build/meson-guest.
#
# Prereq: a built miniBox checkout:
#   meson setup <miniBox>/build/meson-linux <miniBox> && ninja -C <miniBox>/build/meson-linux
#
# Usage: ./waterbox/setup-guest.sh [-m <miniBox dir>]
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
mb="${MINIBOX_DIR:-$HOME/chimera/extern/miniBox}"
while getopts "m:" opt; do
	case "$opt" in
		m) mb="$OPTARG" ;;
		*) exit 2 ;;
	esac
done
shift $((OPTIND - 1))
mb="$(cd "$mb" && pwd)"

# prefer a miniBox build that has the guest sysroot; the cpp flavor carries it too
mbuild=""
for candidate in "$mb/build/meson-linux" "$mb/build/meson-cpp"; do
	[ -f "$candidate/guest-sysroot/lib/libc.a" ] && { mbuild="$candidate"; break; }
done
[ -n "$mbuild" ] || {
	echo "miniBox guest toolchain missing under $mb/build." >&2
	echo "Run: meson setup $mb/build/meson-linux $mb && ninja -C $mb/build/meson-linux" >&2
	exit 1
}
sr="$mbuild/guest-sysroot"

mkdir -p "$root/build"
cross="$root/build/guest-cross.ini"

# The waterbox code-model flags + the musl specs; every compile and link of
# the guest gets these (same recipe as chimera-core-dosbox-x, minus C++).
cat > "$cross" <<EOF
# generated by waterbox/setup-guest.sh - machine-local paths, do not commit
[binaries]
c = 'gcc'
ar = 'ar'
strip = 'strip'

[host_machine]
system = 'linux'
cpu_family = 'x86_64'
cpu = 'x86_64'
endian = 'little'

[properties]
needs_exe_wrapper = true
minibox_dir = '$mb'
minibox_build = '$mbuild'
guest_sysroot = '$sr'

[built-in options]
# strict c99: musl's BSD 'uint' typedef stays hidden and cannot collide
# with m68k.h's '#define uint' (the BizHawk build relied on the same)
c_std = 'c99'
c_args = ['-specs', '$sr/lib/musl-gcc.specs', '-fvisibility=hidden', '-mcmodel=large', '-mstack-protector-guard=global', '-fno-stack-protector', '-fno-pic', '-fno-pie', '-fcf-protection=none', '-DCHIMERA_GUEST', '-I$mb/extern/emulibc', '-I$mb/source/guest/include', '-I$mb/extern/jsmn']
c_link_args = ['-specs', '$sr/lib/musl-gcc.specs']
EOF

meson setup "$root/build/meson-guest" "$root" --cross-file "$cross" "$@" 2>/dev/null \
	|| meson setup --reconfigure "$root/build/meson-guest" "$root" --cross-file "$cross" "$@"
echo "guest build configured: ninja -C build/meson-guest"
